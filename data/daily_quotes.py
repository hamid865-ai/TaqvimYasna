def _build_bank():
    bank = []
    for base, explanation in WISDOM[:67]:
        for quote_tail, meaning_tail in REFLECTIONS:
            bank.append((
                base + " " + quote_tail,
                "اندیشه روز",
                explanation + " " + meaning_tail
            ))

    for arabic, source, meaning in HADITHS:
        bank.append((arabic, source, meaning))

    for verse, source, meaning in POETRY:
        bank.append((verse, source, meaning))

    # تعداد نهایی دقیقاً ۳۶۵ مورد است؛ اگر بانک تغییر کرد، خطا آشکار می‌شود.
    if len(bank) != 365:
        raise ValueError("Daily quote bank must contain exactly 365 entries; found {}".format(len(bank)))
    return bank

QUOTES = _build_bank()

def get_daily_quote():
    """هر روز یک مورد ثابت از بانک ۳۶۵تایی بر اساس روز سال برمی‌گرداند."""
    index = (date.today().timetuple().tm_yday - 1) % 365
    quote, source, meaning = QUOTES[index]
    return quote, source, meaning
